/**
 ******************************************************************************
 * @file    ssd1306.c
 * @brief   0.96 寸 OLED（SSD1306，128x64，I2C）驱动实现
 *
 * 本文件分三部分：
 *   1) 5x7 ASCII 点阵字库（列优先，bit0 = 页内最上面一行）
 *   2) I2C 底层读写（HAL_I2C_Mem_Write）
 *   3) 显存缓冲 + 文字绘制 + 整屏刷新
 ******************************************************************************
 */

#include "ssd1306.h"
#include <string.h>

/* ==========================================================================
 * 一、字库
 * --------------------------------------------------------------------------
 * 字模格式（和 SSD1306 显存的排列方式一致）：
 *   - 每个字符 6 个字节，占 6 列 x 8 行
 *   - 第 0~4 列是字形（宽 5 像素），第 5 列是字符间隔，固定 0x00
 *   - 每个字节代表"某一列竖直方向的 8 个像素"
 *   - 字节的 bit0 = 该列最上面一行，bit1 = 第二行，…… bit7 = 最下面一行
 *   - 字形只占上面 7 行，bit7 恒为 0（所以字与字之间有一行空隙）
 *
 * ⚠️ 这里 bit0 在上的方向，和 SSD1306 数据手册里 GDDRAM 的
 *    "bit0 对应页内第 0 行"是一致的，所以 ShowChar() 里可以直接写进缓冲区。
 *    但另一种常见取模输出是 bit7 在上（Adafruit glcdfont 就是这种），
 *    如果换成那种字库，必须把每个字节做一次位反转（0x01 <-> 0x80），
 *    否则显示出来会上下镜像。这就是第 6 节里"字是倒的"那个坑的根因。
 *
 * 这套字模是用取模软件（PCtoLCD2002，设置：阴码 / 列行式 / 逆向 / C51 格式）
 * 生成的，字形尺寸 5x7。检查办法：SSD1306_DrawPixel(0,0,1) 之后刷新，
 * 亮的应该是屏幕左上角那一个像素。
 *
 * 覆盖范围：ASCII 0x20（空格）~ 0x7E（~），共 95 个字符。
 * 不在此范围内的字符（汉字、0x7F 以上）统一按空白处理，不会输出乱码。
 * ========================================================================== */

typedef struct
{
    uint8_t     Width;      /* 字符占用的列数：(5 字形 + 1 间隔) = 6，空格为 0 */
    char        Char;       /* 对应的 ASCII 字符 */
    uint8_t     Data[6];    /* 6 列的字模数据 */
} SSD1306_FontDef;

